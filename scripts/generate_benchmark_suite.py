"""Generate the injected-defect benchmark suite.

Every case captures its baseline from the CLEAN page (`baseline_url`) and
compares against the same page with `?defect=<mode>` appended (`url`). That
separation is the whole point: the previous benchmark (scratch/suite.bench100.yaml)
pointed both at the defective URL, so baseline and current were pixel-identical
and all 108 injected-defect cases passed trivially — a self-comparison that
cannot fail no matter how broken the page is.

The `none` cases are the control group: baseline and current are both the clean
page, so they SHOULD pass. Everything else SHOULD fail. Those two expectations
are what `scripts/benchmark_report.py` scores.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

BASE_URL = "http://127.0.0.1:8130/demo"

PAGES = ["index", "login", "dashboard"]

LOCALES = [
    ("en-US", "Asia/Kuala_Lumpur"),
    ("zh-CN", "Asia/Shanghai"),
    ("ms-MY", "Asia/Kuala_Lumpur"),
]

# "none" is the control (expected PASS); the rest are injected defects
# (expected FAIL). Each has at least one rule in demo_portal/styles.css —
# z-index-issue had none until it was added alongside this script, which is why
# it could never be detected before.
DEFECT_MODES = [
    "none",
    "missing-cta",
    "shift-card",
    "theme-shift",
    "text-truncation",
    "overlay-obstruction",
    "broken-image",
    "misaligned-fields",
    "unreadable-text",
    "z-index-issue",
]


def build_cases(base_url: str) -> list[dict]:
    cases: list[dict] = []
    index = 0
    for page in PAGES:
        for locale, timezone in LOCALES:
            clean_url = f"{base_url}/{page}.html?lang={locale}"
            for mode in DEFECT_MODES:
                target_url = clean_url if mode == "none" else f"{clean_url}&defect={mode}"
                cases.append(
                    {
                        "name": f"bmk-{index:03d}-{page}-{locale}-{mode}",
                        "url": target_url,
                        "baseline_url": clean_url,
                        "browser": "chromium",
                        "viewport": [1440, 900],
                        "wait_ms": 400,
                        "threshold_pct": 0.25,
                        "pixel_threshold": 20,
                        "min_region_area": 120,
                        "locale": locale,
                        "timezone_id": timezone,
                        "ignore_regions": [],
                    }
                )
                index += 1
    return cases


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="suites/suite.benchmark.yaml")
    parser.add_argument("--base-url", default=BASE_URL)
    parser.add_argument(
        "--comparison-mode",
        default="ai",
        help="ai | pixel | hybrid — the mode every case runs under",
    )
    args = parser.parse_args()

    cases = build_cases(args.base_url)
    payload = {
        "defaults": {"comparison_mode": args.comparison_mode},
        "tests": cases,
    }

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# GENERATED by scripts/generate_benchmark_suite.py — do not edit by hand.\n"
        "#\n"
        "# Each case captures its baseline from `baseline_url` (the clean page) and\n"
        "# compares against `url` (the same page with an injected defect). Cases\n"
        "# ending in `-none` are the control group and should PASS; every other case\n"
        "# should FAIL. Score a run with scripts/benchmark_report.py.\n"
    )
    output.write_text(
        header + yaml.safe_dump(payload, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )

    controls = sum(1 for c in cases if c["name"].endswith("-none"))
    print(f"Wrote {output} — {len(cases)} cases ({controls} control, {len(cases) - controls} injected defects)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
